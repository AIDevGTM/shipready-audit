import jsPDF from "jspdf";
import { AuditResult, ratingConfig } from "@/lib/audit-types";

export function exportAuditToPdf(result: AuditResult) {
  const doc = new jsPDF();
  const margin = 20;
  let y = margin;

  const addText = (text: string, size: number, style: "normal" | "bold" = "normal", color: [number, number, number] = [255, 255, 255]) => {
    doc.setFontSize(size);
    doc.setFont("helvetica", style);
    doc.setTextColor(...color);
    const lines = doc.splitTextToSize(text, 170);
    if (y + lines.length * size * 0.5 > 280) {
      doc.addPage();
      y = margin;
    }
    doc.text(lines, margin, y);
    y += lines.length * size * 0.45 + 2;
  };

  // Dark background
  doc.setFillColor(10, 10, 11);
  doc.rect(0, 0, 210, 297, "F");

  // Title
  addText("ShipReady GTM Audit Report", 20, "bold", [34, 197, 94]);
  addText(result.url, 10, "normal", [150, 150, 150]);
  y += 4;

  // Score
  const scoreColor: [number, number, number] = result.overall_score >= 80 ? [34, 197, 94] : result.overall_score >= 50 ? [245, 158, 11] : [239, 68, 68];
  addText(`Overall Score: ${result.overall_score}/100`, 16, "bold", scoreColor);
  y += 4;

  // Working well
  if (result.working_well.length > 0) {
    addText("What's Working Well", 13, "bold", [34, 197, 94]);
    result.working_well.forEach((item) => {
      addText(`✓ ${item}`, 9, "normal", [200, 200, 200]);
    });
    y += 4;
  }

  // Scorecard
  addText("Scorecard", 14, "bold", [255, 255, 255]);
  y += 2;

  result.categories.forEach((cat) => {
    const rating = ratingConfig[cat.rating];
    const ratingColor: [number, number, number] = cat.rating === "present_clear" ? [34, 197, 94] : cat.rating === "present_weak" ? [245, 158, 11] : [239, 68, 68];
    addText(`${cat.category}: ${rating.label}`, 10, "bold", ratingColor);
    addText(cat.summary, 8, "normal", [180, 180, 180]);

    if (cat.found.length > 0) {
      addText("Found:", 8, "bold", [120, 200, 120]);
      cat.found.forEach((f) => addText(`  • ${f}`, 8, "normal", [170, 170, 170]));
    }
    if (cat.missing.length > 0) {
      addText("Missing:", 8, "bold", [220, 120, 120]);
      cat.missing.forEach((m) => addText(`  • ${m}`, 8, "normal", [170, 170, 170]));
    }
    if (cat.recommendations.length > 0) {
      addText("Recommendations:", 8, "bold", [120, 180, 220]);
      cat.recommendations.forEach((r) => addText(`  • ${r}`, 8, "normal", [170, 170, 170]));
    }
    y += 3;
  });

  // Footer
  addText("Generated by ShipReady", 8, "normal", [100, 100, 100]);

  doc.save(`shipready-audit-${new URL(result.url).hostname}.pdf`);
}
